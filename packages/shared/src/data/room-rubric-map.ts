export interface RoomRubricParts {
  assessmentArea: string
  categories: EsaCategory[]
  subcategories: EsaSubcategory[]
  questions: EsaQuestion[]
  options: EsaQuestionOption[]
}

function rubric(
  assessmentArea: string,
  categories: EsaCategory[],
  subcategories: EsaSubcategory[],
  questions: EsaQuestion[],
  options: EsaQuestionOption[],
): RoomRubricParts {
  return { assessmentArea, categories, subcategories, questions, options }
}

